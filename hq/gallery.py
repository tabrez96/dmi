def _cell(text):
    """Crew-written text in a Markdown table cell: a pipe or a line break would start a new cell or row."""
    return " ".join(str(text or "").split()).replace("|", "\\|")


BADGE = {"draft": "draft", "approved": "approved", "building": "building", "built": "built", "retired": "retired"}


def render_readme(title, screens):
    live = [screen for screen in screens if not screen["retired"]]
    gone = [screen for screen in screens if screen["retired"]]
    lines = [f"# {title}: design library", "",
             ("Generated by Dunder Mifflin HQ; don't edit by hand. Each screen's source is its `screen.html` (or "
              "`screen.svg`) (open it in a browser); `spec.md` describes it. To ask for a change, name the screen ID,"
              ' for example "S02: move the status chips under the title".'), "",
             ("Status: **draft** (UX not approved yet), **approved**, **building** (a ticket for it is in"
              " progress), **built** (every ticket that names it has shipped)."), "",
             "[UX spec and design system](ux.md)", ""]
    if live:
        lines += ["| ID | Screen | Status | Purpose | Tickets | Updated |", "| --- | --- | --- | --- | --- | --- |"]
        for screen in live:
            states = f" (+{len(screen['states'])} states)" if screen["states"] else ""
            tickets = ", ".join(f"T-{ticket_id}" for ticket_id in screen["tickets"]) or "none yet"
            lines.append(f"| {screen['id']} | [{_cell(screen['name'])}](screens/{screen['dir']}/{screen['file']}){states} · "
                         f"[spec](screens/{screen['dir']}/spec.md) | {screen['status']} | {_cell(screen['purpose'])} | "
                         f"{tickets} | {screen['updated']} |")
    else:
        lines.append("No screens yet.")
    if gone:
        lines += ["", "## Retired screens", ""] + [f"- {screen['id']} {screen['name']} (`screens/_retired/{screen['dir']}`)" for screen in gone]
    return "\n".join(lines) + "\n"


