def _url(path):
    """A file path inside a screen's folder, safe in a URL and in a quoted HTML attribute (state names are the crew's)."""
    return html.escape(quote(path), quote=True)


def _page(title, body):
    return (f"<!doctype html><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>"
            f"<title>{html.escape(title)}</title><style>{_CSS}</style>{body}{_FILTER}")


def gallery_product(product):
    """HTML of one product's gallery page, read straight from its repo's design/ folder (nothing is copied).

    product: {"slug","title","state","repo","screens": annotated list_screens()}"""
    live = [screen for screen in product["screens"] if not screen["retired"]]
    grid = []
    for screen in live:
        views = len(screen_slides(screen))
        more = f"<span class=more>{views} views</span>" if views > 1 else ""
        page = f"view/{html.escape(screen['dir'])}"
        grid.append(
            f"<a class=card href='{page}'><div class=thumb><img src='screens/{html.escape(screen['dir'])}/{_url(screen_slides(screen)[0][1])}' "
            f"loading=lazy alt='{html.escape(screen['name'])}'>{more}</div><div class=body><span class=id>{screen['id']}</span> "
            f"{html.escape(screen['name'])}<span class='badge {screen['status']}'>{screen['status']}</span>"
            f"<div>{html.escape(screen['purpose'])}</div>"
            f"<div class=meta>updated {html.escape(screen['updated'] or 'n/a')}"
            f"{f' · the main design and {views - 1} variation' + ('s' if views > 2 else '') if views > 1 else ''}</div>"
            f"</div></a>")
    root = design_dir(product["repo"])
    ux_link = "<a href='ux.md'>UX spec and design system</a> · " if (root / "ux.md").exists() else ""
    logo = ("<img src='brand/logo.png' alt='logo' style='height:72px;margin:8px 0;display:block;background:#fff;"
            "border-radius:10px;padding:6px'>" if (root / "brand" / "logo.png").exists() else "")
    body = (f"<p><a href='../index.html'>All products</a></p><h1>{html.escape(product['title'])}</h1>{logo}"
            f"<p class=sub>{ux_link}{len(live)} screens · product is {html.escape(product['state'].replace('_', ' '))}</p>"
            f"<input id=q placeholder='Filter screens (name, ID, status)'><div class=grid>{''.join(grid) or 'No screens yet.'}</div>")
    return _page(product["title"], body)


def screen_slides(screen):
    """A screen's views for the slideshow: its main design, then each variation (states/*.html) that has a
    screenshot. [(label, path of the PNG inside the screen's folder, path of its HTML)]."""
    main = screen["file"] if screen["file"].endswith(".svg") else "screen.png"   # an SVG screen is its own picture
    slides = [("Main design", main, screen["file"])]
    for state in screen["states"]:
        name = state[:-5]
        if (screen["path"] / "states" / f"{name}.png").exists():
            slides.append((name.replace("-", " ").capitalize(), f"states/{name}.png", f"states/{state}"))
    return slides


def gallery_screen(product, screen):
    """HTML of one screen's page: a slideshow of its main design and every variation. It lives at
    view/<screen folder>, so the files are one level up."""
    folder = f"../screens/{html.escape(screen['dir'])}"
    slides = screen_slides(screen)
    data = json.dumps([{"label": label, "img": f"{folder}/{_url(png)}"} for label, png, _ in slides]).replace("<", "\\u003c")
    strip = "".join(f"<button type=button data-i={i}><img src='{folder}/{_url(png)}' alt=''><span>{html.escape(label)}</span>"
                    f"</button>" for i, (label, png, _) in enumerate(slides))
    body = (f"<p><a href='../index.html'>← {html.escape(product['title'])}</a></p>"
            f"<h1><span class=id>{screen['id']}</span> {html.escape(screen['name'])}</h1><p class=sub>{html.escape(screen['purpose'])}</p>"
            f"<div class=viewer><button type=button class=nav id=prev aria-label='Previous'>‹</button>"
            f"<figure><img id=shot alt='{html.escape(screen['name'])}'><figcaption id=cap></figcaption></figure>"
            f"<button type=button class=nav id=next aria-label='Next'>›</button></div>"
            f"{f'<div class=strip>{strip}</div>' if len(slides) > 1 else ''}"
            f"<p class=meta><a href='{folder}/spec.md'>Spec</a> · use ← → (or swipe) to move between views</p>"
            "<script>const slides=" + data + ";let at=0;const shot=document.getElementById('shot'),"
            "cap=document.getElementById('cap'),tabs=[...document.querySelectorAll('.strip button')];"
            "function show(i){at=(i+slides.length)%slides.length;shot.src=slides[at].img;"
            "cap.textContent=slides[at].label+(slides.length>1?' · '+(at+1)+' of '+slides.length:'');"
            "tabs.forEach((t,n)=>t.classList.toggle('on',n===at));"
            "document.getElementById('prev').hidden=document.getElementById('next').hidden=slides.length<2}"
            "document.getElementById('prev').onclick=()=>show(at-1);document.getElementById('next').onclick=()=>show(at+1);"
            "tabs.forEach(t=>t.onclick=()=>show(+t.dataset.i));"
            "document.addEventListener('keydown',e=>{if(e.key==='ArrowLeft')show(at-1);if(e.key==='ArrowRight')show(at+1)});"
            "let x0=null;shot.addEventListener('touchstart',e=>x0=e.touches[0].clientX,{passive:true});"
            "shot.addEventListener('touchend',e=>{if(x0===null)return;const dx=e.changedTouches[0].clientX-x0;x0=null;"
            "if(Math.abs(dx)>40)show(dx<0?at+1:at-1)});"
            "show(0)</script>")
    return _page(f"{screen['id']} {screen['name']}", body)


def gallery_index(products):
    """HTML of the page that lists every product with a design."""
    cards = []
    for product in products:
        live = [screen for screen in product["screens"] if not screen["retired"]]
        latest = max((screen["updated"] for screen in live if screen["updated"]), default="")
        cards.append(((product['state'] in ('launched', 'building', 'ready_to_launch'), latest),
                      (f"<div class=card><div class=body><a class=id href='{html.escape(product['slug'])}/index.html'>"
                       f"{html.escape(product['title'])}</a><div class=meta>{len(live)} screens · "
                       f"{html.escape(product['state'].replace('_', ' '))} · last change {html.escape(latest or 'n/a')}"
                       "</div></div></div>")))
    index = (f"<h1>Dunder Mifflin design library</h1><p class=sub>{len(products)} products. The files live in each "
             f"product's repo under design/; this page reads them from there.</p>"
             f"<input id=q placeholder='Filter products'><div class=grid>{''.join(card for _, card in sorted(cards, key=lambda entry: entry[0], reverse=True)) or 'No products with designs yet.'}</div>")
    return _page("Dunder Mifflin design library", index)
